/**
 * Normalizes colloquial Thai terms (e.g. "มหาลัย" -> "มหาวิทยาลัย", "มอสยาม" -> "มหาวิทยาลัยสยาม")
 */
export function normalizeThaiQuery(rawQuery: string): string {
  let q = rawQuery.trim().toLowerCase();

  // Common university abbreviations & slangs
  q = q.replace(/มหาลัย/g, 'มหาวิทยาลัย');
  q = q.replace(/มอสยาม|ม\.สยาม|ม สยาม|มอสย|ม\.สย/g, 'มหาวิทยาลัยสยาม');
  q = q.replace(/มอเกษตร|ม\.เกษตร|ม เกษตร/g, 'มหาวิทยาลัยเกษตรศาสตร์');
  q = q.replace(/มอจุฬา|ม\.จุฬา|ม จุฬา/g, 'จุฬาลงกรณ์มหาวิทยาลัย');
  q = q.replace(/มธ\.|มธ|ม\.ธรรมศาสตร์/g, 'มหาวิทยาลัยธรรมศาสตร์');
  q = q.replace(/มอราม|ม\.ราม|ม ราม/g, 'มหาวิทยาลัยรามคำแหง');
  q = q.replace(/มอศาลายา|ม\.มหิดล/g, 'มหาวิทยาลัยมหิดล');

  // Common hospital abbreviations
  q = q.replace(/รพ\.|รพ /g, 'โรงพยาบาล ');

  // Common school abbreviations
  q = q.replace(/รร\.|รร /g, 'โรงเรียน ');

  return q.trim();
}

/**
 * Search local Thai places with fuzzy matching & colloquial alias resolution
 */
export function searchThaiPlaces(rawQuery: string, maxResults = 8): ThaiPlace[] {
  const query = rawQuery.trim().toLowerCase();
  if (!query) return [];

  const normalized = normalizeThaiQuery(query);

  const matched = POPULAR_THAI_PLACES.filter((place) => {
    const nameLower = place.name.toLowerCase();
    const addrLower = place.address.toLowerCase();

    // Direct match against raw query or normalized
    if (nameLower.includes(query) || nameLower.includes(normalized)) return true;
    if (addrLower.includes(query) || addrLower.includes(normalized)) return true;

    // Check aliases
    if (place.aliases) {
      for (const alias of place.aliases) {
        const aliasLower = alias.toLowerCase();
        if (aliasLower.includes(query) || query.includes(aliasLower)) return true;
        if (aliasLower.includes(normalized) || normalized.includes(aliasLower)) return true;
      }
    }

    return false;
  });

  return matched.slice(0, maxResults);
}
